"""从固定的 Purrcept Cel Token 输入生成 Flutter 映射；--check 验证产物未漂移。"""

import argparse
import json
from pathlib import Path


def render(tokens: dict) -> str:
    """仅映射当前设备界面实际使用的 Token，不另立视觉数值。"""
    colors = {
        "brand": "brand", "onBrand": "on-brand", "surface": "surface", "sunken": "surface-sunken",
        "canvas": "canvas", "ink": "ink", "muted": "ink-muted", "active": "active",
        "failed": "failed", "waiting": "waiting",
    }
    lines = ["// Generated by tooling/export_cel.py from design/purrcept-cel.tokens.json.",
             "import 'package:flutter/material.dart';", "", "abstract final class Cel {"]
    for name, key in colors.items():
        lines.append(f"  static const {name} = Color(0xFF{tokens['colors'][key][1:]});")
    for name, group, key in (("radius", "rounded", "md"), ("space", "spacing", "md"), ("contentMax", "spacing", "content-max")):
        lines.append(f"  static const {name} = {float(tokens[group][key].removesuffix('px'))};")
    return "\n".join([*lines, "}", ""])


def main() -> None:
    """生成或检查 Dart Token，输入快照从同级设计仓库的 dist 固定。"""
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    tokens = json.loads((root / "design/purrcept-cel.tokens.json").read_text(encoding="utf-8"))
    output = root / "app/lib/purrcept/tokens.dart"
    expected = render(tokens)
    if args.check:
        if output.read_text(encoding="utf-8") != expected:
            raise SystemExit("Flutter Cel tokens are stale; run tooling/export_cel.py.")
    else:
        output.write_text(expected, encoding="utf-8")


if __name__ == "__main__":
    main()
