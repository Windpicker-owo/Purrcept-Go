"""从固定的 Purrcept Cel v0.4 Token 输入生成 Flutter 映射；--check 验证产物未漂移。"""

import argparse
import json
from pathlib import Path


def render(tokens: dict) -> str:
    """映射共享 Cel v0.4 快照及明确声明的移动端扩展，不在生成器内另立视觉数值。"""
    colors = {
        "brand": "brand",
        "brandFill": "brand-fill",
        "brandPressed": "brand-pressed",
        "brandSignal": "brand-signal",
        "brandContainer": "brand-container",
        "onBrand": "on-brand",
        "onBrandContainer": "on-brand-container",
        "surface": "surface",
        "sunken": "surface-sunken",
        "selected": "surface-selected",
        "canvas": "canvas",
        "atmosphereSky": "atmosphere-sky",
        "atmospherePeach": "atmosphere-peach",
        "paper": "paper",
        "paperSunken": "paper-sunken",
        "paperBlush": "paper-blush",
        "ink": "ink",
        "inkSecondary": "ink-secondary",
        "muted": "ink-muted",
        "inkWarm": "ink-warm",
        "outline": "outline",
        "outlineSubtle": "outline-subtle",
        "outlinePaper": "outline-paper",
        "celShadowSky": "cel-shadow-sky",
        "celShadowPaper": "cel-shadow-paper",
        "blushSignal": "blush-signal",
        "blushContainer": "blush-container",
        "onBlushContainer": "on-blush-container",
        "tapeSignal": "tape-signal",
        "tapeContainer": "tape-container",
        "onTapeContainer": "on-tape-container",
        "active": "active",
        "activeSignal": "active-signal",
        "activeContainer": "active-container",
        "success": "success",
        "successSignal": "success-signal",
        "successContainer": "success-container",
        "waiting": "waiting",
        "waitingSignal": "waiting-signal",
        "waitingContainer": "waiting-container",
        "failed": "failed",
        "failedSignal": "failed-signal",
        "failedContainer": "failed-container",
        "paused": "paused",
        "pausedSignal": "paused-signal",
        "pausedContainer": "paused-container",
    }
    lines = [
        "// Generated by tooling/export_cel.py from design/purrcept-cel.tokens.json.",
        "import 'package:flutter/material.dart';",
        "",
        "abstract final class Cel {",
    ]
    for name, key in colors.items():
        lines.append(f"  static const {name} = Color(0xFF{tokens['colors'][key][1:]});")
    for name, group, key in (
        ("radiusXs", "rounded", "xs"),
        ("radiusSm", "rounded", "sm"),
        ("radius", "rounded", "md"),
        ("radiusLg", "rounded", "lg"),
        ("radiusXl", "rounded", "xl"),
        ("spaceXs", "spacing", "xs"),
        ("spaceSm", "spacing", "sm"),
        ("space", "spacing", "md"),
        ("spaceLg", "spacing", "lg"),
        ("contentMax", "spacing", "content-max"),
    ):
        lines.append(f"  static const {name} = {float(tokens[group][key].removesuffix('px'))};")
    lines.extend(
        [
            "}",
            "",
            "/// Mobile-specific shapes, anatomy and motion; see docs/mobile-experience.md.",
            "abstract final class MobileTokens {",
        ]
    )
    mobile = tokens["mobile"]
    for name, color in mobile["colors"].items():
        lines.append(f"  static const {name} = Color(0xFF{color[1:]});")
    for name, number in mobile["metrics"].items():
        lines.append(f"  static const {name} = {float(number)};")
    for name, milliseconds in mobile["durations"].items():
        lines.append(f"  static const {name} = Duration(milliseconds: {milliseconds});")
    return "\n".join([*lines, "}", ""])


def main() -> None:
    """生成或检查 Dart Token；共享快照与本仓库的 mobile 扩展共同作为输入。"""
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    tokens = json.loads((root / "design/purrcept-cel.tokens.json").read_text(encoding="utf-8"))
    output = root / "app/lib/purrcept/tokens.dart"
    expected = render(tokens)
    if args.check:
        if output.read_text(encoding="utf-8") != expected:
            raise SystemExit("Flutter Cel tokens are stale; run tooling/export_cel.py.")
    else:
        output.write_text(expected, encoding="utf-8")


if __name__ == "__main__":
    main()
